VK_NAMES = {
    0x08: "Backspace", 0x09: "Tab", 0x0D: "Enter", 0x1B: "Esc", 0x20: "Space",
    0x10: "Shift", 0x11: "Ctrl", 0x12: "Alt",
    0x14: "CapsLock", 0x90: "NumLock", 0x91: "ScrollLock",
    0x2C: "PrintScreen", 0x13: "Pause", 0x2D: "Insert", 0x2E: "Delete",
    0x24: "Home", 0x23: "End", 0x21: "PageUp", 0x22: "PageDown",
    0x25: "Left", 0x26: "Up", 0x27: "Right", 0x28: "Down",
    0x5B: "Win", 0x5D: "Menu",
    0x60: "Numpad0", 0x61: "Numpad1", 0x62: "Numpad2", 0x63: "Numpad3",
    0x64: "Numpad4", 0x65: "Numpad5", 0x66: "Numpad6", 0x67: "Numpad7",
    0x68: "Numpad8", 0x69: "Numpad9",
    0x6A: "Numpad*", 0x6B: "Numpad+", 0x6D: "Numpad-", 0x6E: "Numpad.",
    0x6F: "Numpad/",
    0xBA: ";", 0xBB: "=", 0xBC: ",", 0xBD: "-", 0xBE: ".", 0xBF: "/",
    0xC0: "`", 0xDB: "[", 0xDC: "\\", 0xDD: "]", 0xDE: "'",

    0xA0: "Shift", 0xA1: "Shift",   # LShift / RShift
    0xA2: "Ctrl",  0xA3: "Ctrl",    # LCtrl  / RCtrl
    0xA4: "Alt",   0xA5: "Alt",     # LAlt   / RAlt
    0x5C: "Win"
}
for i in range(24):
    VK_NAMES[0x70 + i] = f"F{i + 1}"
for i in range(26):
    VK_NAMES[0x41 + i] = chr(0x41 + i)
for i in range(10):
    VK_NAMES[0x30 + i] = str(i)

VK_NORMALIZE = {
    0xA0: 0x10, 0xA1: 0x10,
    0xA2: 0x11, 0xA3: 0x11,
    0xA4: 0x12, 0xA5: 0x12,
    0x5C: 0x5B,
}

def vk_name(vk: int) -> str:
    return VK_NAMES.get(vk, f"VK(0x{vk:02X})")

def vk_normalize(vk: int) -> int:
    return VK_NORMALIZE.get(vk, vk)